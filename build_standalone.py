#!/usr/bin/env python3
"""Build a single-file GlowUp: inlines CSS, JS, data, icons and manifest hints
into one .html that runs from file:// with zero network requests.

  python3 build_standalone.py  ->  ../glowup-standalone.html
"""
import base64
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.environ.get(
    "GLOWUP_STANDALONE_OUT",
    os.path.join(HERE, "dist", "glowup-standalone.html"),
)
os.makedirs(os.path.dirname(OUT), exist_ok=True)


def read(rel):
    with open(os.path.join(HERE, rel), encoding="utf-8") as fh:
        return fh.read()


def js_safe(text):
    """Make an inline <script> body safe: no </script>, no HTML-comment openers."""
    return (text.replace("</script", "<\\/script")
                .replace("<!--", "<\\!--")
                .replace("]]>", "]]\\>"))


html = read("index.html")
css = read("assets/app.css")
app_js = read("assets/app.js")
fonts_css = read("assets/fonts.css")
data_js = read("data.js")
art_js = read("art.js")
copy_js = read("copy.js")
guides_js = read("guides.js")
plan_js = read("plan.js")
topics_js = read("topics.js")

# ------------------------------------------------------------------ icon (inline SVG)
# One 48×48 SVG replaces icon-192/512/apple-touch: no binary payload, no request.
icon_svg = (
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 96 96" width="96" height="96">'
    '<rect width="96" height="96" rx="22" fill="#1d1d1f"/>'
    '<circle cx="48" cy="48" r="15" fill="#ffffff"/>'
    '<g stroke="#ffffff" stroke-width="5" stroke-linecap="round">'
    '<path d="M48 14v9M48 73v9M14 48h9M73 48h9M24 24l6.4 6.4M65.6 65.6L72 72M72 24l-6.4 6.4M30.4 65.6L24 72"/>'
    "</g></svg>"
)
icon_uri = "data:image/svg+xml;base64," + base64.b64encode(icon_svg.encode()).decode()

# ------------------------------------------------------------------ manifest (for hosts that allow it)
manifest = {
    "name": "GlowUp — Men's Transformation Library",
    "short_name": "GlowUp",
    "description": "Evidence-graded men's fat-loss, muscle and maintenance library — single file, works offline.",
    "start_url": "./glowup-standalone.html",
    "scope": "./",
    "display": "standalone",
    "background_color": "#000000",
    "theme_color": "#000000",
    "lang": "en",
    "icons": [
        {"src": icon_uri, "sizes": "any", "type": "image/svg+xml", "purpose": "any"},
        {"src": icon_uri, "sizes": "any", "type": "image/svg+xml", "purpose": "maskable"},
    ],
}

# ------------------------------------------------------------------ stitch the document
out = html

# 0. standalone flag (read by the pre-paint theme script, so it must come first)
out = out.replace("<!-- glowup:standalone-flag -->",
                  "<script>window.GLOWUP_STANDALONE = true;</script>")
assert "window.GLOWUP_STANDALONE = true" in out

# 1. stylesheet -> <style>
out = out.replace(
    '<link rel="stylesheet" href="assets/app.css" />',
    "<style>\n" + css.strip() + "\n</style>",
)

# 2. icons -> inline data URI (drop PNG links + og image, keep apple-touch)
out = re.sub(r'<link rel="apple-touch-icon"[^>]*>',
             '<link rel="apple-touch-icon" href="' + icon_uri + '" />', out)
out = re.sub(r'<link rel="icon"[^>]*>',
             '<link rel="icon" href="' + icon_uri + '" type="image/svg+xml" />', out)
out = re.sub(r'<link rel="manifest"[^>]*>', "", out)
out = re.sub(r'<meta property="og:image"[^>]*>', "", out)

# 3. data.js + app.js -> inline scripts, with a standalone flag first
inline_scripts = (
    "<script>/* illustrations — generated by art.py */\n" + js_safe(art_js) + "</script>\n"
    "<script>/* editorial copy — human voice */\n" + js_safe(copy_js) + "</script>\n"
    "<script>/* deep-dive guides — plain-English pages */\n" + js_safe(guides_js) + "</script>\n"
    "<script>/* blueprint — phases, daily check, tasks, kit */\n" + js_safe(plan_js) + "</script>\n"
    "<script>/* library — health, fitness, lifestyle, mind */\n" + js_safe(topics_js) + "</script>\n"
    "<script>/* data layer — generated by extract.py */\n" + js_safe(data_js) + "</script>\n"
    "<script>\n" + js_safe(app_js) + "\n</script>"
)
out = out.replace('<script src="art.js"></script>\n<script src="copy.js"></script>\n<script src="guides.js"></script>\n<script src="plan.js"></script>\n<script src="topics.js"></script>\n<script src="data.js"></script>\n<script src="assets/app.js"></script>', inline_scripts)
# 2b. webfonts -> data URIs, so the standalone file makes zero network requests
_fonts_dir = os.path.join(HERE, "assets", "fonts")
_font_inlined = 0
for _fname in sorted(os.listdir(_fonts_dir)) if os.path.isdir(_fonts_dir) else []:
    if not _fname.endswith(".woff2"):
        continue
    with open(os.path.join(_fonts_dir, _fname), "rb") as _fh:
        _b64 = base64.b64encode(_fh.read()).decode("ascii")
    fonts_css = fonts_css.replace(
        'url("/assets/fonts/%s")' % _fname,
        'url("data:font/woff2;base64,%s")' % _b64,
    )
    _font_inlined += 1
out = out.replace(
    '<link rel="stylesheet" href="assets/fonts.css" />',
    "<style>/* WattVision webfonts - inlined for the standalone build */\n" + fonts_css + "</style>",
)

assert "assets/app.css" not in out and "assets/app.js" not in out and 'src="data.js"' not in out and 'src="art.js"' not in out and 'src="copy.js"' not in out and 'src="guides.js"' not in out and 'src="plan.js"' not in out and 'src="topics.js"' not in out

# 4. manifest injected at runtime as a Blob (harmless on file://, used when hosted)
manifest_js = json.dumps(manifest).replace("</", "<\\/")
out = out.replace(
    "</body>",
    "<script>\n(function(){\n"
    "  if (location.protocol === 'file:') return;           // manifest needs an http(s) origin\n"
    "  try {\n"
    "    var m = " + manifest_js + ";\n"
    "    var url = URL.createObjectURL(new Blob([JSON.stringify(m)], {type:'application/manifest+json'}));\n"
    "    var l = document.createElement('link'); l.rel = 'manifest'; l.href = url;\n"
    "    document.head.appendChild(l);\n"
    "  } catch (e) {}\n"
    "})();\n</script>\n</body>",
)

# 5. provenance banner in the source (comment only)
out = out.replace(
    "<head>",
    "<head>\n<!-- GlowUp standalone build: single file, no external requests, works from file://.\n"
    "     Generated from ../research/*.md by extract.py + build_standalone.py. Do not edit by hand. -->",
)

with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
    fh.write(out)

kb = os.path.getsize(OUT) / 1024
print(f"wrote {OUT} ({kb:.0f} KB)")
print(f"  fonts {_font_inlined} inlined")
print(f"  css {len(css)/1024:.0f} KB · js {len(app_js)/1024:.0f} KB · data {len(data_js)/1024:.0f} KB")
_ext = len(re.findall(r'(src|href)="(?!data:|#)', out))
print(f"  external requests: {_ext}")
