/* Screenshots of the Round 9 shell (dark + light). */
const { chromium } = require('playwright-core');
(async () => {
  const b = await chromium.launch({ args: ['--no-sandbox', '--disable-dev-shm-usage'] });
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
  const p = await ctx.newPage();
  await p.goto('file:///home/user/glowup-standalone.html', { waitUntil: 'load' });
  await p.waitForTimeout(500);
  await p.evaluate(() => { document.documentElement.style.scrollBehavior = 'auto'; });
  await p.click('[data-check="protein"]'); await p.click('[data-check="steps"]'); await p.waitForTimeout(250);
  await p.screenshot({ path: 'docs/v9-today.jpg', type: 'jpeg', quality: 80 });
  await p.click('[data-nav="plan"]'); await p.waitForTimeout(400);
  await p.screenshot({ path: 'docs/v9-plan.jpg', type: 'jpeg', quality: 80 });
  await p.evaluate(() => scrollTo(0, 900)); await p.waitForTimeout(400);
  await p.screenshot({ path: 'docs/v9-plan-steps.jpg', type: 'jpeg', quality: 80 });
  await p.evaluate(() => scrollTo(0, 0));
  await p.click('[data-nav="learn"]'); await p.waitForTimeout(350);
  await p.click('[data-subnav="guides"]:visible'); await p.waitForTimeout(250);
  await p.screenshot({ path: 'docs/v9-guides.jpg', type: 'jpeg', quality: 80 });
  await p.click('[data-subnav="articles"]:visible'); await p.waitForTimeout(350);
  await p.screenshot({ path: 'docs/v9-articles.jpg', type: 'jpeg', quality: 80 });
  await p.click('[data-nav="fuel"]'); await p.waitForTimeout(350);
  await p.screenshot({ path: 'docs/v9-fuel.jpg', type: 'jpeg', quality: 80 });
  await p.click('[data-nav="shop"]'); await p.waitForTimeout(350);
  await p.screenshot({ path: 'docs/v9-shop.jpg', type: 'jpeg', quality: 80 });
  await p.click('[data-nav="home"]'); await p.waitForTimeout(300);
  await p.click('#theme-toggle'); await p.waitForTimeout(400);
  await p.screenshot({ path: 'docs/v9-today-light.jpg', type: 'jpeg', quality: 80 });
  await p.click('#theme-toggle'); await p.waitForTimeout(300);
  await p.evaluate(() => localStorage.clear());
  await b.close();
})();
