// Turn data.json into the browser-loadable data.js.
// Kept as a file rather than an inline `node -e` so the quoting stays sane.
import { readFileSync, writeFileSync } from 'node:fs';

const data = JSON.parse(readFileSync('data.json', 'utf8'));
const header = '/* GlowUp data layer — generated by extract.py. Do not edit by hand. */\n';
writeFileSync('data.js', `${header}window.GLOWUP_DATA = ${JSON.stringify(data)};\n`);
console.log(`wrote data.js (${data.articles?.length ?? 0} articles)`);
