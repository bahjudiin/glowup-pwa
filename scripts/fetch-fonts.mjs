// Fetch Inter + JetBrains Mono (latin subset) from Google Fonts and store the
// woff2 files locally, so the app makes no external font requests.
import { writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.argv[2];
const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36';

const CSS_URL =
  'https://fonts.googleapis.com/css2?family=Inter:wght@400;600;700&family=JetBrains+Mono:wght@700&display=swap';

const res = await fetch(CSS_URL, { headers: { 'User-Agent': UA } });
if (!res.ok) {
  console.error('font css fetch failed:', res.status);
  process.exit(1);
}
let css = await res.text();

// Keep only the latin block for each face: the app is latin-only.
const blocks = css.split('@font-face').filter(Boolean);
const wanted = [];
for (const b of blocks) {
  const body = '@font-face' + b;
  if (!/U\+0000-00FF/.test(body)) continue; // latin subset marker
  const fam = (body.match(/font-family:\s*'([^']+)'/) || [])[1];
  const wt = (body.match(/font-weight:\s*(\d+)/) || [])[1];
  const url = (body.match(/url\((https:[^)]+\.woff2)\)/) || [])[1];
  if (!fam || !wt || !url) continue;
  wanted.push({ fam, wt, url });
}

const dir = join(ROOT, 'assets', 'fonts');
mkdirSync(dir, { recursive: true });

const faces = [];
for (const f of wanted) {
  const name = `${f.fam.toLowerCase().replace(/\s+/g, '-')}-${f.wt}.woff2`;
  const bin = Buffer.from(await (await fetch(f.url, { headers: { 'User-Agent': UA } })).arrayBuffer());
  writeFileSync(join(dir, name), bin);
  faces.push({ ...f, file: name, size: bin.length });
  console.log(`  ${name}  ${(bin.length / 1024).toFixed(1)} KB`);
}

const cssOut = faces
  .map(
    (f) => `@font-face {
  font-family: "${f.fam}";
  font-style: normal;
  font-weight: ${f.wt};
  font-display: swap;
  src: url("/assets/fonts/${f.file}") format("woff2");
}`
  )
  .join('\n');

writeFileSync(join(ROOT, 'assets', 'fonts.css'), `/* WattVision — self-hosted webfonts. Generated by scripts/fetch-fonts.mjs. */\n${cssOut}\n`);
console.log(`\nwrote assets/fonts.css with ${faces.length} faces`);
